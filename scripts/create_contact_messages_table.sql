-- SQL script to create the contact_messages table in Supabase

-- Create the contact_messages table
CREATE TABLE IF NOT EXISTS public.contact_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  subject TEXT,
  message TEXT NOT NULL,
  read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- Add comment to the table
COMMENT ON TABLE public.contact_messages IS 'Stores messages submitted through the contact form';

-- Set up Row Level Security (RLS)
ALTER TABLE public.contact_messages ENABLE ROW LEVEL SECURITY;

-- First, drop any existing policies to avoid conflicts
DROP POLICY IF EXISTS "Allow authenticated users full access to contact messages" ON public.contact_messages;
DROP POLICY IF EXISTS "Allow anonymous users to insert contact messages" ON public.contact_messages;

-- Create policies for authenticated users only
CREATE POLICY "Allow authenticated users full access to contact messages" 
  ON public.contact_messages 
  FOR ALL 
  TO authenticated 
  USING (true);

-- Create policy to allow anonymous users to insert messages
-- Using a more explicit policy definition
CREATE POLICY "Allow anonymous users to insert contact messages" 
  ON public.contact_messages 
  FOR INSERT 
  TO anon 
  WITH CHECK (true);
  
-- Create a separate policy for public access
CREATE POLICY "Public insert access to contact_messages"
  ON public.contact_messages
  FOR INSERT
  TO public
  WITH CHECK (true);

-- Create indexes for better performance
CREATE INDEX IF NOT EXISTS contact_messages_read_idx ON public.contact_messages (read);
CREATE INDEX IF NOT EXISTS contact_messages_created_at_idx ON public.contact_messages (created_at DESC);

-- Grant permissions to authenticated users
GRANT ALL ON public.contact_messages TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.contact_messages_id_seq TO authenticated;

-- Grant insert permission to anonymous users
GRANT INSERT ON public.contact_messages TO anon;
GRANT USAGE, SELECT ON SEQUENCE public.contact_messages_id_seq TO anon;



