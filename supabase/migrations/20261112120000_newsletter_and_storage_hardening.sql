-- 1. Newsletter subscribers (footer signup). Written only by /api/newsletter
--    with the service role; admins read/delete from /admin/newsletter.
create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null,
  created_at timestamptz not null default now()
);
create unique index if not exists newsletter_subscribers_email_key
  on public.newsletter_subscribers (lower(email));

alter table public.newsletter_subscribers enable row level security;

drop policy if exists "Admins can read subscribers" on public.newsletter_subscribers;
create policy "Admins can read subscribers" on public.newsletter_subscribers
  for select to authenticated using (true);

drop policy if exists "Admins can delete subscribers" on public.newsletter_subscribers;
create policy "Admins can delete subscribers" on public.newsletter_subscribers
  for delete to authenticated using (true);

-- 2. Storage policies for the two image buckets, defined from scratch.
--    Before this, the `media` bucket let anonymous users upload, overwrite and
--    delete files, and `assets` had no update/delete policy (so removing an
--    image from the admin silently failed). Reads stay public; writes are
--    admin-only.
drop policy if exists "fetch all 1bqp9qb_0" on storage.objects;
drop policy if exists "allow admin 1ps738_0" on storage.objects;
drop policy if exists "allow admin 1ps738_1" on storage.objects;
drop policy if exists "allow admin 1ps738_2" on storage.objects;
drop policy if exists "allow admin 1ps738_3" on storage.objects;
drop policy if exists "Allow authenticated uploads" on storage.objects;
drop policy if exists "Allow public read access" on storage.objects;
drop policy if exists "Public can read site images" on storage.objects;
drop policy if exists "Admins can upload site images" on storage.objects;
drop policy if exists "Admins can update site images" on storage.objects;
drop policy if exists "Admins can delete site images" on storage.objects;

create policy "Public can read site images" on storage.objects
  for select to public using (bucket_id in ('assets', 'media'));
create policy "Admins can upload site images" on storage.objects
  for insert to authenticated with check (bucket_id in ('assets', 'media'));
create policy "Admins can update site images" on storage.objects
  for update to authenticated using (bucket_id in ('assets', 'media'));
create policy "Admins can delete site images" on storage.objects
  for delete to authenticated using (bucket_id in ('assets', 'media'));
