-- Supabase Setup Script for Asmau Ayub Portfolio
-- This script creates all necessary tables and storage buckets

-- Enable necessary extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Categories table
CREATE TABLE IF NOT EXISTS categories (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  content_type TEXT NOT NULL CHECK (content_type IN ('blog', 'research', 'teaching', 'leadership', 'counseling')),
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Contents table (unified content model for blog, research, teaching, leadership, counseling)
CREATE TABLE IF NOT EXISTS contents (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  title TEXT NOT NULL,
  slug TEXT NOT NULL,
  content TEXT,
  excerpt TEXT,
  featured_image TEXT,
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  author_id UUID,
  status TEXT DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  content_type TEXT NOT NULL CHECK (content_type IN ('blog', 'research', 'teaching', 'leadership', 'counseling')),
  meta_description TEXT,
  tags TEXT[]
);

-- Add unique constraint for slug within each content type
ALTER TABLE contents
ADD CONSTRAINT unique_slug_per_content_type UNIQUE (slug, content_type);

-- Media table for uploaded files
CREATE TABLE IF NOT EXISTS media (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  filename TEXT NOT NULL,
  file_path TEXT NOT NULL,
  mime_type TEXT,
  size INTEGER,
  alt_text TEXT,
  caption TEXT,
  uploaded_by UUID,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Contact form submissions
CREATE TABLE IF NOT EXISTS contact_submissions (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  subject TEXT,
  message TEXT NOT NULL,
  status TEXT DEFAULT 'unread' CHECK (status IN ('unread', 'read', 'replied')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- CV requests
CREATE TABLE IF NOT EXISTS cv_requests (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  organization TEXT,
  reason TEXT,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create RLS policies
-- Enable Row Level Security
ALTER TABLE contents ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE media ENABLE ROW LEVEL SECURITY;
ALTER TABLE contact_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE cv_requests ENABLE ROW LEVEL SECURITY;

-- Create policies for public access (read-only for published content)
CREATE POLICY "Public can view published contents" ON contents
  FOR SELECT USING (status = 'published');

CREATE POLICY "Public can view categories" ON categories
  FOR SELECT USING (true);

-- Create policies for authenticated users (admin access)
CREATE POLICY "Authenticated users can manage contents" ON contents
  FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Authenticated users can manage categories" ON categories
  FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Authenticated users can manage media" ON media
  FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Authenticated users can manage contact submissions" ON contact_submissions
  FOR ALL USING (auth.role() = 'authenticated');

CREATE POLICY "Authenticated users can manage cv requests" ON cv_requests
  FOR ALL USING (auth.role() = 'authenticated');

-- Create policy for public to submit contact forms
CREATE POLICY "Public can submit contact forms" ON contact_submissions
  FOR INSERT WITH CHECK (true);

-- Create policy for public to submit CV requests
CREATE POLICY "Public can submit CV requests" ON cv_requests
  FOR INSERT WITH CHECK (true);

-- Create functions and triggers
-- Update updated_at timestamp function
CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create triggers for updated_at
CREATE TRIGGER update_contents_updated_at
BEFORE UPDATE ON contents
FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TRIGGER update_media_updated_at
BEFORE UPDATE ON media
FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TRIGGER update_contact_submissions_updated_at
BEFORE UPDATE ON contact_submissions
FOR EACH ROW EXECUTE FUNCTION update_updated_at();

CREATE TRIGGER update_cv_requests_updated_at
BEFORE UPDATE ON cv_requests
FOR EACH ROW EXECUTE FUNCTION update_updated_at();

